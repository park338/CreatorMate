def _calc_calendar_count(target_days, post_freq):
    """根据目标周期和发布频率计算日历条数。"""
    freq_map = {"每周1条": 1, "每周2-3条": 2.5, "每周3-5条": 4, "日更": 7}
    per_week = freq_map.get(post_freq, 2.5)
    weeks = (target_days or 30) / 7
    count = int(round(weeks * per_week))
    return max(4, min(count, 30))


